"""Generate synthetic compressed decoder input using WSL's existing libzstd.

No installation and no game data. The generated C fixture is portable; WSL is
needed only to regenerate it. Standard: facebook/zstd doc/zstd_compression_format.
"""
import base64
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parent.parent
payload = b"BNSH" + b"WindowSmash/OpenSmash shader worker fixture\0" * 20
payload += b"".join(hashlib.sha256(bytes([n])).digest() for n in range(16))
payload = (payload * 2)[:1536]
program = """
import base64,ctypes,json,sys
z=ctypes.CDLL('libzstd.so.1')
z.ZSTD_versionString.restype=ctypes.c_char_p
z.ZSTD_compressBound.argtypes=[ctypes.c_size_t];z.ZSTD_compressBound.restype=ctypes.c_size_t
z.ZSTD_compress.argtypes=[ctypes.c_void_p,ctypes.c_size_t,ctypes.c_void_p,ctypes.c_size_t,ctypes.c_int];z.ZSTD_compress.restype=ctypes.c_size_t
z.ZSTD_isError.argtypes=[ctypes.c_size_t];z.ZSTD_isError.restype=ctypes.c_uint
data=base64.b64decode(sys.argv[1]);capacity=z.ZSTD_compressBound(len(data));output=ctypes.create_string_buffer(capacity)
n=z.ZSTD_compress(output,capacity,data,len(data),3)
if z.ZSTD_isError(n):raise RuntimeError('ZSTD_compress failed')
print(json.dumps({'version':z.ZSTD_versionString().decode(),'frame':base64.b64encode(output.raw[:n]).decode()}))
"""
result = subprocess.run(["wsl.exe", "--exec", "python3", "-c", program, base64.b64encode(payload).decode()], capture_output=True, text=True, timeout=30, check=True)
metadata = json.loads(result.stdout)
frame = base64.b64decode(metadata["frame"])
if len(frame) >= len(payload):
    raise RuntimeError("Fixture did not compress; review payload")
descriptor = frame[4]
single = bool(descriptor & 0x20)
content_size_bytes = (1 if single else 0, 2, 4, 8)[descriptor >> 6]
dictionary_bytes = (0, 1, 2, 4)[descriptor & 3]
block_offset = 5 + (0 if single else 1) + dictionary_bytes + content_size_bytes
block_type = (int.from_bytes(frame[block_offset:block_offset + 3], "little") >> 1) & 3
if block_type != 2:
    raise RuntimeError("Fixture must exercise a compressed block, not only raw/RLE")
def array(name, data):
    rows = ["    " + ",".join(f"0x{x:02x}" for x in data[n:n+16]) for n in range(0, len(data), 16)]
    return f"static const uint8_t {name}[]={{\n" + ",\n".join(rows) + "\n};\n"
folder = ROOT / "diagnostics/fixtures"
folder.mkdir(parents=True, exist_ok=True)
(folder / "worker_compressed_fixture.h").write_text("#pragma once\n#include <stdint.h>\n// Synthetic data, generated by Make-ZstdWorkerFixture.py; no game bytes.\n" + array("worker_compressed_frame", frame) + array("worker_compressed_payload", payload), encoding="utf-8")
(folder / "worker_compressed_fixture.json").write_text(json.dumps({"generator": "Make-ZstdWorkerFixture.py", "zstdVersion": metadata["version"], "level": 3, "blockType": block_type, "inputBytes": len(payload), "compressedBytes": len(frame), "payloadSha256": hashlib.sha256(payload).hexdigest(), "frameSha256": hashlib.sha256(frame).hexdigest()}, indent=2) + "\n", encoding="utf-8")
print(f"Generated synthetic fixture: {len(payload)} -> {len(frame)} bytes with libzstd {metadata['version']}")
